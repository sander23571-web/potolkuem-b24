# --- B24 API ---
def b24_json(method, params):
    data = json.dumps(params).encode()
    req = urllib.request.Request(WEBHOOK + method, data=data)
    req.add_header('Content-Type', 'application/json')
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())

def get_children_names(folder_id):
    """Возвращает dict {name_upper: (id, type, exact_name)}"""
    items = {}
    start = 0
    while True:
        res = b24_json('disk.folder.getchildren', {'id': folder_id, 'start': start})
        for item in res.get('result', []):
            items[item['NAME'].upper()] = (item['ID'], item['TYPE'], item['NAME'])
        if len(res.get('result', [])) < 50:
            break
        start += 50
        time.sleep(0.2)
    return items

def create_folder(parent_id, name):
    res = b24_json('disk.folder.addsubfolder', {'id': parent_id, 'data': {'NAME': name}})
    return res['result']['ID']

def upload_file(folder_id, filename, content):
    """Загружает файл через multipart/form-data."""
    boundary = b'----B24UploadBoundary'
    body = b''
    # part: data (JSON с именем файла)
    body += b'--' + boundary + b'\r\n'
    body += b'Content-Disposition: form-data; name="data"\r\n\r\n'
    body += json.dumps({'NAME': filename}).encode('utf-8') + b'\r\n'
    # part: file
    body += b'--' + boundary + b'\r\n'
    body += f'Content-Disposition: form-data; name="file"; filename="{filename}"\r\n'.encode('utf-8')
    body += b'Content-Type: application/octet-stream\r\n\r\n'
    body += content + b'\r\n'
    body += b'--' + boundary + b'--\r\n'

    url = WEBHOOK + 'disk.folder.uploadfile' + f'?id={folder_id}'
    req = urllib.request.Request(url, data=body)
    req.add_header('Content-Type', f'multipart/form-data; boundary={boundary.decode()}')
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.loads(r.read())

# --- Кеш папок: path_tuple → folder_id ---
folder_cache = {(): ROOT_FOLDER_ID}

def get_or_create_folder(path_parts):
    """path_parts — кортеж компонентов пути относительно ROOT."""
    if path_parts in folder_cache:
        return folder_cache[path_parts]

    # Идём сверху вниз
    for i in range(1, len(path_parts) + 1):
        sub = path_parts[:i]
        if sub in folder_cache:
            continue
        parent_id = folder_cache[path_parts[:i-1]]
        raw_name = path_parts[i-1]
        # Применяем маппинг
        b24_name = FOLDER_MAP.get(raw_name, raw_name).strip()

        # Смотрим существующие папки
        children = get_children_names(parent_id)
        time.sleep(0.2)

        found_id = None
        # Ищем по точному имени или маппингу
        if b24_name.upper() in children:
            found_id = children[b24_name.upper()][0]
        elif raw_name.strip().upper() in children:
            found_id = children[raw_name.strip().upper()][0]
        else:
            # Создаём
            print(f'  📁 Создаю папку: {"/".join(sub)}')
            found_id = create_folder(parent_id, b24_name)
            time.sleep(0.3)

        folder_cache[sub] = found_id

    return folder_cache[path_parts]


# --- Основной цикл ---
print(f'=== Загрузка {len(ONLY_IN_ZIP)} файлов на Б24 ===\n')

ok = 0
err = 0

with zipfile.ZipFile(ZIP_PATH) as zf:
    for zip_rel_path in ONLY_IN_ZIP:
        # Полный путь в zip: ДОГОВОРЫ/...
        zip_full = 'ДОГОВОРЫ/' + zip_rel_path
        filename = os.path.basename(zip_rel_path)
        folder_parts = tuple(zip_rel_path.replace('\\', '/').split('/')[:-1])

        try:
            # Найти/создать папку на Б24
            folder_id = get_or_create_folder(folder_parts)

            # Читаем файл из zip
            content = zf.read(zip_full)

            # Загружаем
            res = upload_file(folder_id, filename, content)
            if res.get('result'):
                file_id = res['result'].get('ID', '?')
                print(f'  ✅ id={file_id}: {zip_rel_path}')
                ok += 1
            else:
                print(f'  ❌ {zip_rel_path}: {res}')
                err += 1

        except Exception as e:
            print(f'  ❌ {zip_rel_path}: {e}')
            err += 1

        time.sleep(0.4)

print(f'\n=== ИТОГ ===')
print(f'  Загружено: {ok}')
print(f'  Ошибок:    {err}')
